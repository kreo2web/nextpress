/**
 * Writes the reference pages of the NextPress docs from what the code already knows, so they are
 * never out of date: every block (from the block catalog) and every MCP tool (from the MCP
 * server's own tool list). Run on each release:
 *
 *   cd packages/mcp && npx tsx scripts/generate-docs-reference.ts
 *
 * Output: content/nextpress-docs/reference/ in the docs folder's format (front matter, then the
 * MDX the docs import reads). Guides are written by hand; these files are overwritten.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";
import { BLOCK_CATALOG } from "../../../shared/block-catalog/index.js";
import type { BlockCatalogCategory } from "../../../shared/block-catalog/types.js";
import { createNextpress } from "@nextpress-org/sdk";
import { createMcpServer } from "../src/create-mcp-server.js";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "../../../content/nextpress-docs/reference");
const NOTICE = "# Generated by packages/mcp/scripts/generate-docs-reference.ts. Edit the code it reads, not this file.";

/** Blocks that are the docs frame or kept only for old pages: never offered, so not listed. */
const NOT_LISTED = new Set(["docs/shell", "docs/page", "core/docs-layout"]);

const CATEGORY_TITLES: Record<BlockCatalogCategory, string> = {
	basic: "Basic",
	layout: "Layout",
	media: "Media",
	form: "Form",
	post: "Post",
	advanced: "Advanced",
	docs: "Docs",
};

/** Escapes what MDX would read as code or a tag in prose, leaving `inline code` as written. */
const safeProse = (text: string): string =>
	text
		.split("`")
		.map((part, index) => (index % 2 === 1 ? part : part.replace(/[{}]/g, (brace) => `\\${brace}`).replace(/</g, "&lt;")))
		.join("`");

const frontMatter = ({ title, description, slug, kind, order }: { title: string; description: string; slug: string; kind: "page" | "group"; order: number }): string =>
	["---", NOTICE, `title: ${title}`, `description: ${description}`, `slug: ${slug}`, `kind: ${kind}`, `order: ${order}`, "---", ""].join("\n");

function blocksPage(): string {
	const listed = BLOCK_CATALOG.filter((entry) => !NOT_LISTED.has(entry.name));
	const sections = (Object.keys(CATEGORY_TITLES) as BlockCatalogCategory[]).flatMap((category) => {
		const entries = listed.filter((entry) => entry.category === category);
		if (entries.length === 0) return [];
		const rows = entries.map((entry) =>
			[`### ${entry.label}`, "", `\`${entry.name}\`${entry.kind === "container" ? " · holds other blocks" : ""}`, "", safeProse(entry.description), "", safeProse(entry.agentNote), ""].join("\n"),
		);
		return [`## ${CATEGORY_TITLES[category]}`, "", ...rows];
	});
	return [
		frontMatter({ title: "Blocks", description: "Every block you can add to a page, what it is for, and its name for the SDK and MCP.", slug: "blocks-reference", kind: "page", order: 1 }),
		"Pages are built from these blocks. The name under each title (such as `core/heading`) is what the SDK, MCP tools and page files use.",
		"",
		...sections,
	].join("\n");
}

type ListedTool = { name: string; description?: string; annotations?: { readOnlyHint?: boolean; destructiveHint?: boolean } };

async function listMcpTools(): Promise<ListedTool[]> {
	// The tool list needs no site: the client never sends a request while tools are listed.
	const sdk = createNextpress({ baseUrl: "https://example.invalid", apiKey: "npk_live_reference", siteId: "00000000-0000-4000-8000-000000000000" });
	const server = createMcpServer({ client: sdk });
	const client = new Client({ name: "docs-reference", version: "0.0.0" });
	const [clientSide, serverSide] = InMemoryTransport.createLinkedPair();
	await Promise.all([client.connect(clientSide), server.server.connect(serverSide)]);
	const { tools } = await client.listTools();
	await client.close();
	await server.close();
	return [...tools].sort((a, b) => a.name.localeCompare(b.name));
}

function toolsPage(tools: ListedTool[]): string {
	const rows = tools.map((tool) => {
		const kind = tool.annotations?.destructiveHint ? "Deletes" : tool.annotations?.readOnlyHint ? "Reads only" : "Changes content";
		return [`### ${tool.name}`, "", `*${kind}*`, "", safeProse((tool.description ?? "").trim()), ""].join("\n");
	});
	return [
		frontMatter({ title: "MCP tools", description: "Every tool the NextPress MCP server gives an agent, and what each one does.", slug: "mcp-tools", kind: "page", order: 2 }),
		"These are the tools an agent sees when it connects to the NextPress MCP server. To set the server up, see [MCP server](/docs/developers/mcp-server).",
		"",
		"## Tools",
		"",
		...rows,
	].join("\n");
}

async function main(): Promise<void> {
	mkdirSync(OUT, { recursive: true });
	writeFileSync(join(OUT, "_group.md"), frontMatter({ title: "Reference", description: "Lists made from NextPress itself: blocks and MCP tools.", slug: "reference", kind: "group", order: 7 }));
	writeFileSync(join(OUT, "blocks.md"), blocksPage());
	const tools = await listMcpTools();
	writeFileSync(join(OUT, "mcp-tools.md"), toolsPage(tools));
	console.log(`Wrote ${OUT}: blocks.md (${BLOCK_CATALOG.length - NOT_LISTED.size} blocks), mcp-tools.md (${tools.length} tools)`);
}

main().catch((error: Error) => {
	console.error("[docs-reference] Could not write the reference pages", { atFunction: "generateDocsReference", error });
	process.exitCode = 1;
});
